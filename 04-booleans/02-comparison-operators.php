<?php
// Comparison Operators

// Run: php 04-booleans/02-comparison-operators.php

// Comparison operators compare two values and return true or false

$a = 5;
$b = 10;

echo "Equal (==): " . ($a == $b ? "true" : "false") . "\n";
echo "Not equal (!=): " . ($a != $b ? "true" : "false") . "\n";
echo "Greater than (>): " . ($a > $b ? "true" : "false") . "\n";
echo "Less than (<): " . ($a < $b ? "true" : "false") . "\n";
echo "Greater or equal (>=): " . ($a >= $b ? "true" : "false") . "\n";
echo "Less or equal (<=): " . ($a <= $b ? "true" : "false") . "\n";
?>

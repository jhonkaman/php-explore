<?php
// While

// Run: php 08-loops/02-while.php

// The while loop executes code as long as a condition is true

$count = 1;

while ($count <= 5) {
    echo "Count: " . $count . "\n";
    $count++;
}

echo "\n";

$num = 10;

while ($num > 0) {
    echo "Countdown: " . $num . "\n";
    $num--;
}
?>

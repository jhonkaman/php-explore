<?php
// Assignment Operators

// Run: php 03-numbers/05-assignment-operators.php

// Assignment operators assign values to variables, and can combine operations

$x = 10;
echo "x = " . $x . "\n";

$x += 5;
echo "x += 5: " . $x . "\n";

$x -= 3;
echo "x -= 3: " . $x . "\n";

$x *= 2;
echo "x *= 2: " . $x . "\n";

$x /= 4;
echo "x /= 4: " . $x . "\n";
?>

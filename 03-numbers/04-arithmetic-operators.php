<?php
// Arithmetic Operators

// Run: php 06-operators/01-arithmetic-operators.php

// Arithmetic operators perform mathematical operations on numbers

$a = 10;
$b = 3;

echo "$a + $b: " . ($a + $b) . "\n";
echo "-: " . ($a - $b) . "\n";
echo "*: " . ($a * $b) . "\n";
echo "/: " . ($a / $b) . "\n";
echo "%: " . ($a % $b) . "\n";
echo "**: " . ($a ** $b) . "\n";
?>
